"""Fetch the open pack's fonts and write their descriptors and the
pack.d/fonts.ini fragment.

The fonts are SIL Open Font License typefaces from the Google Fonts
repository, pinned to one commit and checked by SHA-256.  They are not in
this repository; the sizes below are 640x480 pixels, set so the x-height
and baseline match the original fonts (see asset-packs.md).
"""
import argparse
import hashlib
import os
import urllib.request

ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
ap.add_argument("--pack", default=os.path.expanduser("~/flibustier-openpack"),
                help="the pack to write into")
args = ap.parse_args()
PACK = args.pack
COMMIT = "9862abc066c9b83bf84c3e8ed1fc2d8d48f9bbf0"
URL = "https://raw.githubusercontent.com/google/fonts/%s/ofl/" % COMMIT

# family directory -> (name, authors, files and their SHA-256)
FAMILIES = {
    "imfellenglish": ("IM Fell English", "Igino Marini", {
        "IMFeENrm28P.ttf":
        "fe9705bbde51af802719246d4608d08d37bde956ab99d9a590da996a5221a24c",
        "OFL.txt":
        "2a3ca501fc4d5efcad9798531e3e06962b1e20c60e464f6cbd6c17630112c773",
    }),
    "pirataone": ("Pirata One", "Rodrigo Fuenzalida, Nicolas Massi", {
        "PirataOne-Regular.ttf":
        "5347a2e155589ecf667d4b766613c8ee003edde9f83717fd24c09599a4b1ecc0",
        "OFL.txt":
        "e8ad3f3de5baeff6bac6e711d8c406e0a6b8a61d2944741532d8965d893a2681",
    }),
}

# font ID -> (font file, line height, size, baseline, use)
FONTS = [
    ("pirate1", "IMFeENrm28P.ttf", 25, 21, 17, "titles and menus"),
    ("pirate2", "IMFeENrm28P.ttf", 15, 14, 11, "body text"),
    ("pirate3", "IMFeENrm28P.ttf", 14, 12, 11, "small text"),
    ("pirate4", "PirataOne-Regular.ttf", 30, 21, 21, "large headings"),
    ("caps", "PirataOne-Regular.ttf", 34, 36, 31, "drop capitals"),
]


def fetch(family, name, sha):
    out = os.path.join(PACK, "fonts", family, name)
    if os.path.exists(out):
        data = open(out, "rb").read()
    else:
        with urllib.request.urlopen(URL + family + "/" + name) as r:
            data = r.read()
    if hashlib.sha256(data).hexdigest() != sha:
        raise SystemExit("%s/%s: SHA-256 mismatch" % (family, name))
    with open(out, "wb") as fp:
        fp.write(data)


where = {}
for family, (_, _, files) in FAMILIES.items():
    os.makedirs(os.path.join(PACK, "fonts", family), exist_ok=True)
    for name, sha in files.items():
        fetch(family, name, sha)
        where[name] = family
os.makedirs(os.path.join(PACK, "pack.d"), exist_ok=True)

lines = ["# The fonts: SIL Open Font License typefaces (fonts/*/OFL.txt),",
         "# fetched from github.com/google/fonts at %s" % COMMIT[:12],
         "# by tools/font_pack.py.", ""]
for family, (name, authors, _) in FAMILIES.items():
    lines.append("# %s, by %s" % (name, authors))
lines += ["", "[assets]"]
for fid, ttf, height, size, baseline, use in FONTS:
    family = where[ttf]
    with open(os.path.join(PACK, "fonts", family, fid + ".font"), "w") as fp:
        fp.write("# Generated by tools/font_pack.py: %s.\n"
                 "[font]\nfile = %s\nheight = %d\nsize = %g\n"
                 "baseline = %g\n" % (use, ttf, height, size, baseline))
    lines.append("font/%s = fonts/%s/%s.font" % (fid, family, fid))
with open(os.path.join(PACK, "pack.d", "fonts.ini"), "w") as fp:
    fp.write("\n".join(lines) + "\n")
print(len(FONTS), "fonts")
