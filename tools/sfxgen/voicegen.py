"""Voice the open pack's spoken sound effects with Dia2.

Each line of voices.toml is spoken by Dia2 (Nari Labs, Apache 2.0) from
its text alone, never from the original's recordings, on a GPU host
reached by ssh (Dia2 runs outside ComfyUI, in its own Python environment
there: DIR/venv, with dia2, whisper-timestamped and an ffmpeg in its
bin/ for the reference voice).  The takes come back, their
silence trimmed, normalised, cut only past 1.5 times the original's
length, converted to OGG Vorbis, and written to the pack with a
provenance record each and the pack.d/voice.ini fragment.

    voicegen.py [--host HOST] [--dir DIR] [--pack DIR] [--seed N]
                [--force] [ID ...]
"""

import argparse
import datetime
import json
import os
import subprocess
import sys
import tempfile
import tomllib

HERE = os.path.dirname(os.path.abspath(__file__))
REMOTE = "/tmp/flibustier-voices"


def finish(wav, out, length):
    """Trim the silence at both ends, normalise, cut past 1.5 x length
    with a short fade, OGG Vorbis."""
    cap = length * 1.5
    af = ("silenceremove=start_periods=1:start_threshold=-45dB,"
          "areverse,silenceremove=start_periods=1:start_threshold=-45dB,"
          "areverse,loudnorm=I=-16:TP=-1.5,"
          "atrim=0:%.3f,afade=t=out:st=%.3f:d=0.04" % (cap, cap - 0.04))
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", wav, "-af", af,
                    "-ar", "48000", "-c:a", "libvorbis", "-q:a", "6", out],
                   check=True)


def git_rev():
    try:
        return subprocess.run(["git", "-C", HERE, "rev-parse", "--short",
                               "HEAD"], capture_output=True, text=True,
                              check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def write_fragment(pack, spec):
    lines = ["# Generated by tools/sfxgen/voicegen.py; see provenance/.",
             "# Voices spoken by Dia2 (Nari Labs, Apache 2.0) from text alone",
             "# (no original recording as input), but for those a person",
             "# recorded ('recorded' in voices.toml).", "", "[assets]"]
    for v in spec["voice"]:
        f = v["id"] + ".ogg"
        if os.path.exists(os.path.join(pack, f)):
            lines.append("%s = %s" % (v["id"], f))
    os.makedirs(os.path.join(pack, "pack.d"), exist_ok=True)
    with open(os.path.join(pack, "pack.d", "voice.ini"), "w") as fp:
        fp.write("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--host", default="framework2")
    ap.add_argument("--dir", default="dia2",
                    help="Dia2's directory on the host (relative to home)")
    ap.add_argument("--pack", default=os.path.expanduser(
        "~/flibustier-openpack"))
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--force", action="store_true")
    ap.add_argument("ids", nargs="*")
    a = ap.parse_args()
    with open(os.path.join(HERE, "voices.toml"), "rb") as f:
        spec = tomllib.load(f)
    todo = [v for v in spec["voice"] if not a.ids or v["id"] in a.ids]
    if a.ids and len(todo) != len(set(a.ids)):
        sys.exit("unknown id among: " + " ".join(a.ids))
    todo = [v for v in todo if not v.get("recorded")]
    todo = [v for v in todo if a.force or not os.path.exists(
        os.path.join(a.pack, v["id"] + ".ogg"))]
    os.makedirs(os.path.join(a.pack, "sound"), exist_ok=True)
    os.makedirs(os.path.join(a.pack, "provenance"), exist_ok=True)
    r = spec["render"]
    if todo:
        jobs = [{"out": "%s/%s.wav" % (REMOTE, v["id"].split("/")[1]),
                 "seed": a.seed, "text": v["text"]} for v in todo]
        with tempfile.TemporaryDirectory() as tmp:
            with open(os.path.join(tmp, "jobs.json"), "w") as fp:
                json.dump(jobs, fp)
            subprocess.run(["ssh", "-o", "BatchMode=yes", a.host,
                            "mkdir -p " + REMOTE], check=True)
            subprocess.run(["scp", "-q", os.path.join(HERE, "dia_say.py"),
                            os.path.join(tmp, "jobs.json"),
                            "%s:%s/" % (a.host, REMOTE)], check=True)
            subprocess.run(["ssh", "-o", "BatchMode=yes", a.host,
                            "cd %s && PATH=$PWD/venv/bin:$PATH "
                            "HF_TOKEN=$(cat ~/.cache/huggingface/"
                            "token 2>/dev/null) venv/bin/python %s/dia_say.py"
                            " %s %s %s %s/jobs.json %s" % (
                                a.dir, REMOTE, r["repo"], r["cfg"],
                                r["temperature"], REMOTE,
                                r.get("voice", ""))], check=True)
            for v, j in zip(todo, jobs):
                wav = os.path.join(tmp, os.path.basename(j["out"]))
                subprocess.run(["scp", "-q", "%s:%s" % (a.host, j["out"]),
                                wav], check=True)
                name = v["id"].replace("/", "-")
                finish(wav, os.path.join(a.pack, v["id"] + ".ogg"),
                       float(v["length"]))
                rec = {"id": v["id"], "file": v["id"] + ".ogg",
                       "model": r["repo"], "text": v["text"],
                       "seed": a.seed, "cfg": r["cfg"],
                       "temperature": r["temperature"],
                       "voice": r.get("voice"),
                       "voice_source": r.get("voice_source"),
                       "length": v["length"],
                       "tool": "tools/sfxgen/voicegen.py@" + git_rev(),
                       "date": datetime.date.today().isoformat()}
                with open(os.path.join(a.pack, "provenance",
                                       name + ".json"), "w") as fp:
                    json.dump(rec, fp, indent=1)
                print(v["id"], flush=True)
    write_fragment(a.pack, spec)


if __name__ == "__main__":
    main()
